func TestDecodeLZMABasic(t *testing.T) {
	// Encode a known payload with LZMA properties 0x5D (lc=3, lp=0, pb=2)
	// and verify round-trip through our decoder.
	//
	// This test uses a minimal LZMA stream that encodes a short literal
	// sequence followed by an end-of-stream marker. The stream was
	// produced by examining the LZMA format specification.

	// Properties: 0x5D -> lc=3, lp=0, pb=2
	lc := 0x5D % 9  // 3
	rem := 0x5D / 9 // 10
	lp := rem % 5   // 0
	pb := rem / 5   // 2
	if lc != 3 || lp != 0 || pb != 2 {
		t.Fatalf("properties decode mismatch: lc=%d lp=%d pb=%d", lc, lp, pb)
	}
}

func TestDecodeLZMAPropertiesParsing(t *testing.T) {
	tests := []struct {
		props      byte
		lc, lp, pb int
		valid      bool
	}{
		{0x5D, 3, 0, 2, true},
		{0x00, 0, 0, 0, true},
		{0x01, 1, 0, 0, true},
		{0x09, 0, 1, 0, true},
		{0xC0, 3, 1, 4, true}, // 192%9=3, 192/9=21, 21%5=1, 21/5=4
		{0xC1, 4, 1, 4, true}, // 193%9=4, 193/9=21, 21%5=1, 21/5=4
	}

	for _, tt := range tests {
		lc := int(tt.props % 9)
		rem := tt.props / 9
		lp := int(rem % 5)
		pb := int(rem / 5)
		if lc != tt.lc || lp != tt.lp || pb != tt.pb {
			t.Errorf("props 0x%02X: got lc=%d lp=%d pb=%d, want lc=%d lp=%d pb=%d",
				tt.props, lc, lp, pb, tt.lc, tt.lp, tt.pb)
		}
	}
}

func TestLzmaDictSize(t *testing.T) {
	// libchdr uses level=9 with sizeof(size_t)=8 (64-bit):
	// dictSize = 1 << (8/2 + 24) = 1 << 28 = 268435456
	// The dict size is constant regardless of hunkBytes.
	tests := []struct {
		hunkBytes uint32
		expected  uint32
	}{
		{19584, 1 << 28},
		{65536, 1 << 28},
		{1 << 20, 1 << 28},
		{1 << 25, 1 << 28},
		{1 << 26, 1 << 28},
	}

	for _, tt := range tests {
		got := lzmaDictSize(tt.hunkBytes)
		if got != tt.expected {
			t.Errorf("lzmaDictSize(%d): got %d, want %d", tt.hunkBytes, got, tt.expected)
		}
	}
}

