func TestCopyMatchWrap(t *testing.T) {
	// Verify dictionary wrapping during match copy.
	d := &lzmaDecoder{
		dictSize: 8,
		dict:     make([]byte, 8),
		dictPos:  6,
		rep0:     0, // distance 0 means copy from dictPos-1
	}
	// Place known bytes at the end of the dict
	d.dict[5] = 0xAA
	d.dict[6] = 0xBB
	d.dict[7] = 0xCC

	var out []byte
	d.copyMatch(4, &out)

	// rep0=0 means distance 1: copy previous byte each time
	// dictPos=6, prev=dict[5]=0xAA, then keeps copying 0xAA
	expected := []byte{0xAA, 0xAA, 0xAA, 0xAA}
	if !bytes.Equal(out, expected) {
		t.Errorf("copyMatch output: got %v, want %v", out, expected)
	}
}

func TestDecodeLZMAMatchedLiteral(t *testing.T) {
	// "ABCDABCE" - forces a match on "ABCD" then a matched literal for 'E'
	// Compressed with lc=3, lp=0, pb=2, dict_size=65536
	stream := []byte{0x00, 0x20, 0x90, 0x84, 0x76, 0xC3, 0xF4, 0xAF, 0x7E, 0x88, 0xCE, 0xDF, 0xFF, 0xCD, 0xF2, 0x00, 0x00}
	expected := []byte{0x41, 0x42, 0x43, 0x44, 0x41, 0x42, 0x43, 0x45}

	result, err := decodeLZMA(stream, 0, 0x5D, 65536)
	if err != nil {
		t.Fatalf("decodeLZMA error: %v", err)
	}
	if !bytes.Equal(result, expected) {
		for i := 0; i < len(result) && i < len(expected); i++ {
			if result[i] != expected[i] {
				t.Errorf("byte %d: got 0x%02X, want 0x%02X", i, result[i], expected[i])
				break
			}
		}
		if len(result) != len(expected) {
			t.Errorf("length: got %d, want %d", len(result), len(expected))
		}
		t.Errorf("got %x, want %x", result, expected)
	}
}

