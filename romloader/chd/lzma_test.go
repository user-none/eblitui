func TestRangeDecoderDecodeBit(t *testing.T) {
	// Verify that the range decoder can decode bits with proper
	// probability adaptation.
	data := []byte{0x00, 0x00, 0x00, 0x00, 0x00, 0xFF, 0xFF, 0xFF}
	rd := &rangeDecoder{
		src:  data,
		pos:  5,
		rng:  0xFFFFFFFF,
		code: 0x00000000,
	}
	prob := uint16(1024)
	// With code=0 and prob=1024, bound = (0xFFFFFFFF >> 11) * 1024
	// code(0) < bound, so result should be 0 and prob increases
	bit := rd.decodeBit(&prob)
	if bit != 0 {
		t.Errorf("expected bit 0 with code=0, got %d", bit)
	}
	if prob <= 1024 {
		t.Errorf("prob should increase after decoding 0, got %d", prob)
	}
}

func TestRangeDecoderDecodeTree(t *testing.T) {
	// Simple tree decode test with deterministic data.
	// All zeros in code means we keep taking the 0 branch.
	data := make([]byte, 32)
	rd := &rangeDecoder{
		src:  data,
		pos:  5,
		rng:  0xFFFFFFFF,
		code: 0x00000000,
	}
	probs := makeProbs(16) // 4-bit tree needs 16 entries (1..15 used)
	val := rd.decodeTree(probs, 4)
	// With code=0, all bits should decode as 0 -> value 0
	if val != 0 {
		t.Errorf("decodeTree with zero code: got %d, want 0", val)
	}
}

